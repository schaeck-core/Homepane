#!/usr/bin/env python3
"""Embed the pictures in resources/screensaver/ into the firmware:
writes app/generated/builtin_pictures.c (one byte array per picture).

Usage: scripts/gen_builtin_pictures.py   then commit the generated file.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PICTURES = [('default.jpg', 'builtin_screensaver_default')]


def main():
    out = ['/* Generated by scripts/gen_builtin_pictures.py from resources/screensaver: do not edit. */',
           '#include <stddef.h>', '']
    for name, symbol in PICTURES:
        data = open(os.path.join(ROOT, 'resources', 'screensaver', name), 'rb').read()
        out.append(f'const unsigned char {symbol}[] = {{')
        for i in range(0, len(data), 20):
            out.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 20]) + ',')
        out.append('};')
        out.append(f'const size_t {symbol}_size = sizeof({symbol});')
        out.append('')
    path = os.path.join(ROOT, 'app', 'generated', 'builtin_pictures.c')
    with open(path, 'w') as f:
        f.write('\n'.join(out))
    print(os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
