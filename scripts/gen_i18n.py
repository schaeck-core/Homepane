#!/usr/bin/env python3
"""Generate the UI string tables from app/i18n/*.lang.

One file per language (key = text, see app/i18n/en.lang for the format).
English (en.lang) is the reference: it defines every key; other languages
fall back to it for keys they lack (reported as a warning).

Writes
  app/i18n_keys.h            enum tr_key_t (TR_<KEY>) and TR__COUNT
  app/generated/i18n_strings.c  the tables (one per language) and their metadata

Checks: every placeholder set ({0}, {1}, ...) equals the English one; keys a
language has that English lacks are errors.

Usage: scripts/gen_i18n.py [--check]   (--check: fail if the outputs are stale;
a ctest runs it)
"""
import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG_DIR = os.path.join(ROOT, 'app', 'i18n')
KEYS_H = os.path.join(ROOT, 'app', 'i18n_keys.h')
TABLES_C = os.path.join(ROOT, 'app', 'generated', 'i18n_strings.c')
REFERENCE = 'en'
PLACEHOLDER = re.compile(r'\{(\d+)\}')


def parse(path):
    meta, strings = {}, {}
    with open(path, encoding='utf-8') as f:
        for n, raw in enumerate(f, 1):
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            if '=' not in line:
                sys.exit(f'{path}:{n}: expected "key = text"')
            key, value = (part.strip() for part in line.split('=', 1))
            value = value.replace('\\n', '\n')
            if key.startswith('@'):
                meta[key[1:]] = value
            elif key in strings:
                sys.exit(f'{path}:{n}: duplicate key {key}')
            else:
                strings[key] = value
    return meta, strings


def load_all():
    langs = {}
    for path in sorted(glob.glob(os.path.join(LANG_DIR, '*.lang'))):
        code = os.path.splitext(os.path.basename(path))[0]
        langs[code] = parse(path)
    if REFERENCE not in langs:
        sys.exit('app/i18n/en.lang (the reference language) is missing')
    return langs


def enum_name(key):
    return 'TR_' + re.sub(r'[^A-Za-z0-9]', '_', key).upper()


def c_string(s):
    out = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    return f'"{out}"'


def generate(langs):
    ref = langs[REFERENCE][1]
    keys = list(ref.keys())
    errors, warnings = [], []
    for code, (meta, strings) in langs.items():
        for key in strings:
            if key not in ref:
                errors.append(f'{code}.lang: {key} is not in en.lang')
            elif set(PLACEHOLDER.findall(strings[key])) != set(PLACEHOLDER.findall(ref[key])):
                errors.append(f'{code}.lang: {key} has other placeholders than en.lang')
        missing = [k for k in keys if k not in strings]
        if missing:
            warnings.append(f'{code}.lang: {len(missing)} keys fall back to English ({", ".join(missing[:5])}...)')
    if errors:
        sys.exit('\n'.join(errors))

    h = ['/* Generated by scripts/gen_i18n.py from app/i18n/<code>.lang: do not edit. */',
         '#ifndef I18N_KEYS_H', '#define I18N_KEYS_H', '', 'typedef enum {',
         '    TR__NONE = 0, /* no text: optional fields (tr() returns "") */']
    h += [f'    {enum_name(k)}, /* {ref[k][:60].replace("*/", "* /")} */' for k in keys]
    h += ['    TR__COUNT', '} tr_key_t;', '', '#endif /* I18N_KEYS_H */', '']

    c = ['/* Generated by scripts/gen_i18n.py from app/i18n/<code>.lang: do not edit. */',
         '#include <stddef.h>', '#include "../i18n.h"', '']
    codes = list(langs.keys())
    for code in codes:
        strings = langs[code][1]
        c.append(f'static const char *const s_{code}[TR__COUNT] = {{')
        c.append('    "", /* TR__NONE */')
        for k in keys:
            c.append(f'    {c_string(strings[k]) if k in strings else "NULL"}, /* {k} */')
        c.append('};')
        c.append('')
    c.append('const i18n_language_t i18n_languages[] = {')
    for code in codes:
        meta = langs[code][0]
        c.append(f'    {{"{code}", {c_string(meta.get("name", code))}, '
                 f'{c_string(meta.get("decimal", "."))}, s_{code}}},')
    c.append('};')
    c.append(f'const int i18n_language_count = {len(codes)};')
    c.append('')
    return '\n'.join(h), '\n'.join(c), warnings


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    keys_h, tables_c, warnings = generate(load_all())
    for w in warnings:
        print('warning:', w)
    if args.check:
        stale = [p for p, text in ((KEYS_H, keys_h), (TABLES_C, tables_c))
                 if not os.path.exists(p) or open(p, encoding='utf-8').read() != text]
        if stale:
            sys.exit('stale, run scripts/gen_i18n.py: ' + ', '.join(os.path.relpath(p, ROOT) for p in stale))
        print('i18n tables up to date')
        return
    for path, text in ((KEYS_H, keys_h), (TABLES_C, tables_c)):
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
